create or replace function public.register_stock_entry(
  p_material_id uuid,
  p_quantity numeric,
  p_document_number text default null,
  p_notes text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_material public.materials%rowtype;
  v_profile public.profiles%rowtype;
  v_before numeric(14,2);
  v_after numeric(14,2);
  v_movement_id bigint;
begin
  if not public.can_operate_warehouse(auth.uid()) then
    raise exception 'Seu perfil não possui permissão para registrar entradas de estoque.';
  end if;

  if p_material_id is null then
    raise exception 'Selecione o material.';
  end if;

  if p_quantity is null or p_quantity <= 0 then
    raise exception 'A quantidade de entrada deve ser maior que zero.';
  end if;

  select * into v_profile
  from public.profiles
  where id = auth.uid();

  select * into v_material
  from public.materials
  where id = p_material_id
  for update;

  if v_material.id is null then
    raise exception 'Material não encontrado.';
  end if;

  v_before := coalesce(v_material.stock_quantity, 0);
  v_after := v_before + p_quantity;

  update public.materials
  set stock_quantity = v_after,
      stock_updated_at = now()
  where id = p_material_id;

  insert into public.inventory_movements (
    material_id, movement_type, quantity,
    balance_before, balance_after,
    document_number, notes,
    actor_id, actor_name, actor_email
  ) values (
    p_material_id, 'entry', p_quantity,
    v_before, v_after,
    nullif(btrim(coalesce(p_document_number, '')), ''),
    nullif(btrim(coalesce(p_notes, '')), ''),
    auth.uid(), v_profile.full_name, v_profile.email
  )
  returning id into v_movement_id;

  return v_movement_id;
end;
$$;

revoke all on function public.register_stock_entry(uuid, numeric, text, text)
  from public, anon, authenticated;
grant execute on function public.register_stock_entry(uuid, numeric, text, text)
  to authenticated;

-- Cadastro/edição de material pelo almoxarifado, com estoque inicial auditado.
create or replace function public.save_warehouse_material(
  p_material_id uuid,
  p_nome text,
  p_codigo text,
  p_categoria text,
  p_unidade text,
  p_quantidade_minima numeric,
  p_descricao text,
  p_ativo boolean,
  p_initial_stock numeric default 0
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_material_id uuid;
  v_initial numeric(14,2) := greatest(coalesce(p_initial_stock, 0), 0);
begin
  if not public.can_operate_warehouse(auth.uid()) then
    raise exception 'Seu perfil não possui permissão para cadastrar ou editar materiais.';
  end if;

  if nullif(btrim(coalesce(p_nome, '')), '') is null then
    raise exception 'Informe o nome do material.';
  end if;
  if nullif(btrim(coalesce(p_unidade, '')), '') is null then
    raise exception 'Informe a unidade de medida.';
  end if;
  if p_quantidade_minima is not null and p_quantidade_minima < 0 then
    raise exception 'A quantidade mínima não pode ser negativa.';
  end if;

  if p_material_id is null then
    insert into public.materials (
      nome, codigo, categoria, unidade, quantidade_minima, descricao, ativo, created_by
    ) values (
      btrim(p_nome), nullif(btrim(coalesce(p_codigo, '')), ''),
      nullif(btrim(coalesce(p_categoria, '')), ''), btrim(p_unidade),
      p_quantidade_minima, nullif(btrim(coalesce(p_descricao, '')), ''),
      coalesce(p_ativo, true), auth.uid()
    ) returning id into v_material_id;

    if v_initial > 0 then
      perform public.register_stock_entry(
        v_material_id,
        v_initial,
        null,
        'Estoque inicial cadastrado junto com o material.'
      );
    end if;
  else
    update public.materials
    set nome = btrim(p_nome),
        codigo = nullif(btrim(coalesce(p_codigo, '')), ''),
        categoria = nullif(btrim(coalesce(p_categoria, '')), ''),
        unidade = btrim(p_unidade),
        quantidade_minima = p_quantidade_minima,
        descricao = nullif(btrim(coalesce(p_descricao, '')), ''),
        ativo = coalesce(p_ativo, true)
    where id = p_material_id
    returning id into v_material_id;

    if v_material_id is null then
      raise exception 'Material não encontrado.';
    end if;
  end if;

  return v_material_id;
end;
$$;

revoke all on function public.save_warehouse_material(uuid, text, text, text, text, numeric, text, boolean, numeric)
  from public, anon, authenticated;
grant execute on function public.save_warehouse_material(uuid, text, text, text, text, numeric, text, boolean, numeric)
  to authenticated;

