-- -----------------------------------------------------------------------------
-- 1. Saldo físico atual por material
-- -----------------------------------------------------------------------------

alter table public.materials
  add column if not exists stock_quantity numeric(14,2) not null default 0;

alter table public.materials
  add column if not exists stock_updated_at timestamptz;

update public.materials
set stock_quantity = greatest(coalesce(stock_quantity, 0), 0)
where stock_quantity is null or stock_quantity < 0;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'materials_stock_quantity_check'
      and conrelid = 'public.materials'::regclass
  ) then
    alter table public.materials
      add constraint materials_stock_quantity_check
      check (stock_quantity >= 0);
  end if;
end $$;

create index if not exists materials_stock_idx
  on public.materials (ativo, stock_quantity, nome);

-- -----------------------------------------------------------------------------
-- 2. Livro razão do estoque
-- -----------------------------------------------------------------------------

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  material_id uuid not null references public.materials(id) on delete restrict,
  movement_type text not null,
  quantity numeric(14,2) not null check (quantity > 0),
  balance_before numeric(14,2) not null check (balance_before >= 0),
  balance_after numeric(14,2) not null check (balance_after >= 0),
  document_number text,
  notes text,
  request_id uuid references public.requests(id) on delete set null,
  delivery_id uuid references public.deliveries(id) on delete set null,
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text,
  actor_email text,
  created_at timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'inventory_movements_type_check'
      and conrelid = 'public.inventory_movements'::regclass
  ) then
    alter table public.inventory_movements
      add constraint inventory_movements_type_check
      check (movement_type in ('entry', 'dispatch'));
  end if;
end $$;

create index if not exists inventory_movements_material_created_idx
  on public.inventory_movements (material_id, created_at desc);
create index if not exists inventory_movements_request_idx
  on public.inventory_movements (request_id, created_at desc);
create index if not exists inventory_movements_delivery_idx
  on public.inventory_movements (delivery_id, created_at desc);

alter table public.inventory_movements enable row level security;

drop policy if exists inventory_movements_select_internal on public.inventory_movements;
create policy inventory_movements_select_internal
on public.inventory_movements for select to authenticated
using (public.can_view_network_operations(auth.uid()));

-- Movimentações são gravadas exclusivamente pelas RPCs security definer.
revoke all on table public.inventory_movements from anon, authenticated;
grant select on table public.inventory_movements to authenticated;

-- -----------------------------------------------------------------------------
-- 3. Catálogo por perfil
--    Escola: somente material ativo e com saldo > 0.
--    SME/Almoxarifado/Admin: catálogo completo e saldo atual.
-- -----------------------------------------------------------------------------

drop policy if exists materials_select_scoped_v5 on public.materials;
drop policy if exists materials_select_stock_scoped_v52 on public.materials;
create policy materials_select_stock_scoped_v52
on public.materials for select to authenticated
using (
  public.is_active_user(auth.uid())
  and (
    (
      public.current_school_id(auth.uid()) is not null
      and ativo = true
      and stock_quantity > 0
    )
    or public.can_view_network_operations(auth.uid())
  )
);

-- O almoxarifado passa a poder manter o catálogo; estoque não é alterado
-- diretamente por INSERT/UPDATE, somente pelas RPCs abaixo.
drop policy if exists materials_insert_system_admin on public.materials;
drop policy if exists materials_update_system_admin on public.materials;
drop policy if exists materials_insert_warehouse_v52 on public.materials;
drop policy if exists materials_update_warehouse_v52 on public.materials;

create policy materials_insert_warehouse_v52
on public.materials for insert to authenticated
with check (public.can_operate_warehouse(auth.uid()));

create policy materials_update_warehouse_v52
on public.materials for update to authenticated
using (public.can_operate_warehouse(auth.uid()))
with check (public.can_operate_warehouse(auth.uid()));

-- Restringe a alteração direta das colunas de saldo.
revoke all on table public.materials from anon, authenticated;
grant select on table public.materials to authenticated;
grant delete on table public.materials to authenticated;

